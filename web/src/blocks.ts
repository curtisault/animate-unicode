// The wedges U+1FB3C–1FB67, each a polygon as digit pairs: x in halves of the cell, y in thirds.
const WEDGES = ["130302", "230302", "130301", "230301", "001303", "1020230301", "20230301", "1020230302", "20230302", "10202303", "21230302", "222313", "222303", "212313", "212303", "202313", "0010212303", "00212303", "0010222303", "00222303", "00102303", "22230301", "0020231302", "00202302", "0020231301", "00202301", "00202313", "001001", "002001", "001002", "002002", "001003", "00202102", "0020221303", "00202203", "0020211303", "00202103", "00201303", "102021", "002021", "102022", "002022", "102023", "00202201"];

const shapes = new Map<number, Shape>();
OCTANTS.forEach((cp, mask) => mask && shapes.set(cp, { w: 2, h: 4, mask }));
// Sextants count up through the 2 × 3 masks, leaving out the four that are a space, a half block or a full block.
for (let mask = 1; mask < 63; mask++) {
  if (mask === 21 || mask === 42) continue;
  shapes.set(0x1fb00 + mask - 1 - (mask > 21 ? 1 : 0) - (mask > 42 ? 1 : 0), { w: 2, h: 3, mask });
}
WEDGES.forEach((p, i) => {
  const poly: number[] = [];
  for (let k = 0; k < p.length; k += 2) poly.push(Number(p[k]) / 2, Number(p[k + 1]) / 3);
  shapes.set(0x1fb3c + i, { poly });
});

/** The shape a canvas fills for a code point, or undefined to draw it from the font. */
export const shapeOf = (cp: number): Shape | undefined => shapes.get(cp);
