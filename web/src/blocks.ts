/*
 * blocks: the shapes of the block-like glyphs a canvas draws itself rather
 * than from the font, so cells of them tile with no seams: the octants (and
 * the halves, quadrants and quarter blocks that stand in for some), the
 * sextants and the wedges. A font's block glyphs stop a hair short of the
 * cell here and there; a solid logo or a scene shows every gap.
 */

